import { Metadata } from "next";
import ResetPassword from "./resetPassword";
import { ResetPasswordUserData } from "@/app/services/auth.service";

export const metadata: Metadata = {
  title: "Reset Password",
  description: "Generated by Samundra Nepal",
};

export default async function page({
  searchParams,
}: {
  searchParams: Promise<{ resetToken?: string }>;
}) {
  const { resetToken } = await searchParams;

  if (!resetToken) {
    return <div>Invalid reset link</div>;
  }

  const userData = await ResetPasswordUserData({ resetToken: resetToken });

  return (
    <div className="min-h-screen w-full bg-green-100 flex items-center justify-center px-4">
      {userData.code === 201 ? (
        <ResetPassword data={userData.message} />
      ) : (
        <div className="w-full max-w-md bg-white rounded-2xl shadow-xl p-8 text-center">
          <div className="mx-auto mb-5 flex h-16 w-16 items-center justify-center rounded-full bg-red-100">
            <svg
              xmlns="http://www.w3.org/2000/svg"
              className="h-8 w-8 text-red-500"
              fill="none"
              viewBox="0 0 24 24"
              stroke="currentColor"
              strokeWidth={2}
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M6 18L18 6M6 6l12 12"
              />
            </svg>
          </div>

          <h1 className="text-2xl font-semibold text-gray-900">
            Reset Link Invalid
          </h1>

          <p className="mt-3 text-gray-500">
            {userData.message ||
              "This password reset link is invalid or has expired."}
          </p>
        </div>
      )}
    </div>
  );
}
