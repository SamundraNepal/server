import Media from "@/app/components/media_display/media";
import { GetFiles } from "@/app/services/media.data.service";
import { Metadata } from "next";
import { cookies } from "next/headers";

export const metadata: Metadata = {
  title: "Videos",
  description: "Generated by Samundra Nepal",
};

export default async function Page() {
  const cookieStore = await cookies();
  const authToken = cookieStore.get("auth_token");

  // api call get images data
  const filesData = await GetFiles(authToken, 1, 50, "Videos");

  return (
    <Media
      data={filesData?.filesData?.data}
      mediaType="Videos"
      displayName="Videos"
      albumID=""
    />
  );
}
