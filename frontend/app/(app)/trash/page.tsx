import { Metadata } from "next";
import Media from "@/app/components/media_display/media";
import { cookies } from "next/headers";
import { GetTrashFiles } from "@/app/services/media.data.service";

export const metadata: Metadata = {
  title: "Trash",
  description: "Generated by Samundra Nepal",
};

export default async function Page() {
  const cookieStore = await cookies();
  const authToken = cookieStore.get("auth_token");

  // api call get images data
  const filesData = await GetTrashFiles(authToken);
  return (
    <Media
      data={filesData?.files.mediaFiles}
      mediaType="Trash"
      displayName="Trash"
      albumID=""
    />
  );
}
