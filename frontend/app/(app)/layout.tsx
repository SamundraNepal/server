import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { UserProvider } from "../context/UserContext";
import { cookies } from "next/headers";
import { GetHomePageDataUser } from "../services/auth.service";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "My Gallery",
  description: "Generated by Samundra Nepal",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const cookieStore = await cookies();
  const authToken = cookieStore.get("auth_token")?.value;
  const userData = await GetHomePageDataUser(authToken!);

  return <UserProvider initialUser={userData.message}>{children}</UserProvider>;
}
